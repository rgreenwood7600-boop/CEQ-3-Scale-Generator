"use strict";

/*
 * Builds the ARB Class 3 examiner marksheet as a PDF in the browser.
 * jsPDF and its table plugin are loaded from a CDN in index.html.
 * The scale lists themselves are not touched.
 */

(function () {
    var GROUP_A = "Generated by the exam administrator from Group A";
    var GROUP_B = "Generated by the exam administrator from Group B";

    var MARKSHEET_SCALES = [
        { label: "Major Scales", comments: [GROUP_A, GROUP_A, GROUP_A, GROUP_B, GROUP_B] },
        { label: "Harmonic Minor Scales", comments: [GROUP_A, GROUP_B] },
        { label: "Melodic Minor Scales", comments: [GROUP_A, GROUP_B] },
        { label: "Chromatic Scale", comments: ["Starting note selected by the candidate"] },
        { label: "Major Arpeggios", comments: [GROUP_A, GROUP_B] },
        { label: "Minor Arpeggios", comments: [GROUP_A, GROUP_B] },
        { label: "Dominant 7ths (in the key of)", comments: [GROUP_A, GROUP_B] },
        { label: "Diminished 7ths", comments: [GROUP_A, GROUP_B] },
        { label: "Whole Tone Scale", comments: [GROUP_A, GROUP_B] }
    ];

    var NAVY = [0, 33, 71];
    var INK = [28, 36, 48];
    var MUTED = [62, 76, 90];
    var HEADER = [217, 226, 243];
    var GREY = [217, 217, 217];
    var LEFT = 12;
    var RIGHT = 12;
    var WIDTH = 186;

    function pdfLibrary() {
        if (!window.jspdf || typeof window.jspdf.jsPDF !== "function") {
            throw new Error("The PDF library did not load.");
        }
        return window.jspdf.jsPDF;
    }

    function fieldValue(id) {
        var field = document.getElementById(id);
        return field ? field.value.trim() : "";
    }

    function dateText(input) {
        if (!input || !input.value) {
            return "";
        }
        var parts = input.value.split("-").map(Number);
        if (parts.length !== 3 || parts.some(function (part) { return !part; })) {
            return input.value;
        }
        var parsed = new Date(parts[0], parts[1] - 1, parts[2]);
        if (Number.isNaN(parsed.getTime())) {
            return input.value;
        }
        return parsed.toLocaleDateString();
    }

    function readSheetFromPage() {
        var dateInput = document.getElementById("candidateDate");
        return {
            assessmentId: document.getElementById("assessmentId").textContent.trim(),
            instrumentName: document.getElementById("selectedInstrument").textContent.trim(),
            details: [
                [
                    { label: "Number", value: fieldValue("candidateNumber") },
                    { label: "Rank", value: fieldValue("candidateRank") },
                    { label: "Name", value: fieldValue("candidateName") },
                    { label: "Date", value: dateText(dateInput) }
                ],
                [
                    { label: "Instrument", value: document.getElementById("selectedInstrument").textContent.trim() },
                    { label: "Band", value: fieldValue("candidateBand") }
                ]
            ],
            rows: Array.prototype.map.call(document.querySelectorAll("#assessmentBody tr"), function (row) {
                return {
                    cells: Array.prototype.map.call(row.children, function (child) {
                        return { text: child.textContent.replace(/\s+/g, " ").trim() };
                    })
                };
            })
        };
    }

    function generatedScale(sheet, index) {
        var row = sheet.rows[index];
        if (!row || row.cells.length < 5) {
            return { note: "", octaves: "", articulation: "" };
        }
        return {
            note: row.cells[1].text,
            octaves: row.cells[2].text,
            articulation: row.cells[4].text
        };
    }

    function downloadName(sheet) {
        var instrument = (sheet.instrumentName || "")
            .replace(/[^A-Za-z0-9]+/g, "-")
            .replace(/^-|-$/g, "");
        if (/^ARB3-\d{8}-\d{4}$/.test(sheet.assessmentId)) {
            return instrument && instrument !== "Not-selected"
                ? sheet.assessmentId + "-" + instrument + ".pdf"
                : sheet.assessmentId + ".pdf";
        }
        return "ARB-Class-3-Scales.pdf";
    }

    function gridStyles() {
        return {
            font: "helvetica",
            fontSize: 8,
            textColor: INK,
            lineColor: INK,
            lineWidth: 0.2,
            cellPadding: 1.3,
            valign: "middle",
            overflow: "linebreak"
        };
    }

    function drawCentered(doc, text, y, size, style) {
        doc.setFont("helvetica", style || "bold");
        doc.setFontSize(size);
        doc.setTextColor(NAVY[0], NAVY[1], NAVY[2]);
        doc.text(text, 105, y, { align: "center" });
    }

    function banner(doc, text, y) {
        doc.setFillColor(GREY[0], GREY[1], GREY[2]);
        doc.setDrawColor(INK[0], INK[1], INK[2]);
        doc.setLineWidth(0.2);
        doc.rect(LEFT, y, WIDTH, 8, "FD");
        doc.setFont("helvetica", "bold");
        doc.setFontSize(11);
        doc.setTextColor(INK[0], INK[1], INK[2]);
        doc.text(text, LEFT + 2, y + 5.4);
        return y + 8;
    }

    function buildMarksheetPdf(sheet) {
        var JsPDF = pdfLibrary();
        var doc = new JsPDF({ unit: "mm", format: "a4" });
        if (typeof doc.autoTable !== "function") {
            throw new Error("The PDF table library did not load.");
        }

        doc.setProperties({
            title: "ARB Class 3",
            subject: sheet.assessmentId,
            creator: "RMSM ARB Assessment Generator"
        });

        var number = "";
        var rank = "";
        var name = "";
        var date = "";
        var instrument = sheet.instrumentName === "Not selected" ? "" : (sheet.instrumentName || "");
        var band = "";
        if (sheet.details && sheet.details[0]) {
            number = sheet.details[0][0].value;
            rank = sheet.details[0][1].value;
            name = sheet.details[0][2].value;
            date = sheet.details[0][3].value;
        }
        if (sheet.details && sheet.details[1]) {
            band = sheet.details[1][1].value;
        }

        drawCentered(doc, "The Royal Military School of Music", 16, 16, "bold");
        drawCentered(doc, "ARB Class 3", 24, 18, "bold");
        drawCentered(doc, "Brass/Woodwind/Percussion", 31, 12, "bold");
        doc.setFont("helvetica", "normal");
        doc.setFontSize(9);
        doc.setTextColor(MUTED[0], MUTED[1], MUTED[2]);
        doc.text("Assessment ID: " + sheet.assessmentId, 105, 37, { align: "center" });

        doc.autoTable({
            startY: 41,
            margin: { left: LEFT, right: RIGHT },
            theme: "grid",
            styles: gridStyles(),
            body: [
                [
                    "Number: " + number,
                    "Rank: " + rank,
                    "Name: " + name,
                    "Date: " + date
                ],
                [
                    "Instrument: " + instrument,
                    { content: "Band: " + band, colSpan: 3 }
                ]
            ],
            columnStyles: {
                0: { cellWidth: 62 },
                1: { cellWidth: 36 },
                2: { cellWidth: 44 },
                3: { cellWidth: 44 }
            }
        });

        var body = [];
        var generatedIndex = 0;
        MARKSHEET_SCALES.forEach(function (section) {
            section.comments.forEach(function (comment, index) {
                var generated = generatedScale(sheet, generatedIndex);
                generatedIndex += 1;
                var row = [
                    generated.note,
                    generated.octaves,
                    generated.articulation,
                    comment,
                    ""
                ];
                if (index === 0) {
                    row.unshift({
                        content: section.label,
                        rowSpan: section.comments.length,
                        styles: { fontStyle: "bold", valign: "middle" }
                    });
                }
                body.push(row);
            });
        });

        doc.autoTable({
            startY: doc.lastAutoTable.finalY + 4,
            margin: { left: LEFT, right: RIGHT },
            theme: "grid",
            styles: Object.assign(gridStyles(), { fontSize: 7.5, cellPadding: 1.1 }),
            headStyles: {
                fillColor: HEADER,
                textColor: NAVY,
                fontStyle: "bold",
                halign: "left"
            },
            head: [["Discipline", "Note", "Octaves", "Articulation", "Comments", "Score"]],
            body: body,
            columnStyles: {
                0: { cellWidth: 32 },
                1: { cellWidth: 18 },
                2: { cellWidth: 22 },
                3: { cellWidth: 28 },
                4: { cellWidth: 62, textColor: MUTED },
                5: { cellWidth: 24 }
            }
        });

        doc.autoTable({
            startY: doc.lastAutoTable.finalY + 4,
            margin: { left: LEFT, right: RIGHT },
            tableWidth: 48,
            theme: "grid",
            styles: Object.assign(gridStyles(), { fontStyle: "bold", halign: "center", fontSize: 10 }),
            body: [["Mark", "/20"]],
            columnStyles: {
                0: { cellWidth: 28 },
                1: { cellWidth: 20 }
            }
        });

        doc.addPage();
        var piecesTop = banner(doc, "Pieces or Songs:", 14);
        doc.setDrawColor(INK[0], INK[1], INK[2]);
        doc.setLineWidth(0.3);
        doc.rect(LEFT, piecesTop, WIDTH, 250);

        doc.addPage();
        var continuedTop = banner(doc, "Pieces or Songs Continued:", 14);
        var continuedHeight = 78;
        doc.rect(LEFT, continuedTop, WIDTH, continuedHeight);
        doc.autoTable({
            startY: continuedTop + 40,
            margin: { left: 118, right: 16 },
            tableWidth: 76,
            theme: "grid",
            styles: Object.assign(gridStyles(), { fontSize: 8, cellPadding: 1.2 }),
            body: [
                ["Notational Accuracy\nand Fluency", "/30"],
                ["Technical\nFacility", "/30"],
                ["Communication\nand Interpretation", "/30"],
                [{ content: "Sub Total", styles: { fontStyle: "bold" } }, { content: "/90", styles: { fontStyle: "bold", halign: "center" } }]
            ],
            columnStyles: {
                0: { cellWidth: 52 },
                1: { cellWidth: 24, halign: "center" }
            }
        });

        var sightTop = banner(doc, "Sight Reading:", doc.lastAutoTable.finalY + 8);
        var sightHeight = 32;
        doc.rect(LEFT, sightTop, WIDTH, sightHeight);
        doc.autoTable({
            startY: sightTop + sightHeight - 12,
            margin: { left: 168, right: 16 },
            tableWidth: 26,
            theme: "grid",
            styles: Object.assign(gridStyles(), { fontStyle: "bold", halign: "center", fontSize: 10 }),
            body: [["/20"]]
        });

        var transpositionTop = banner(doc, "Transposition/Rudiments and Beat Patterns:", doc.lastAutoTable.finalY + 8);
        var transpositionHeight = 32;
        doc.rect(LEFT, transpositionTop, WIDTH, transpositionHeight);
        doc.autoTable({
            startY: transpositionTop + transpositionHeight - 12,
            margin: { left: 168, right: 16 },
            tableWidth: 26,
            theme: "grid",
            styles: Object.assign(gridStyles(), { fontStyle: "bold", halign: "center", fontSize: 10 }),
            body: [["/20"]]
        });

        doc.autoTable({
            startY: transpositionTop + transpositionHeight + 6,
            margin: { left: LEFT, right: RIGHT },
            theme: "grid",
            styles: Object.assign(gridStyles(), { fontSize: 10, cellPadding: 1.6 }),
            body: [
                [{ content: "Marks:", colSpan: 2, styles: { fillColor: GREY, fontStyle: "bold" } }],
                ["Scales", { content: "/20", styles: { halign: "right" } }],
                ["Pieces", { content: "/90", styles: { halign: "right" } }],
                ["Sight Reading", { content: "/20", styles: { halign: "right" } }],
                ["Transposition", { content: "/20", styles: { halign: "right" } }],
                [{ content: "Total", styles: { fontStyle: "bold" } }, { content: "/150", styles: { halign: "right", fontStyle: "bold" } }],
                ["Pass: 70% | Merit: 80% | Distinction: 90%", { content: "/100%", styles: { halign: "right" } }]
            ],
            columnStyles: {
                0: { cellWidth: 130 },
                1: { cellWidth: 56 }
            }
        });

        doc.autoTable({
            startY: doc.lastAutoTable.finalY + 4,
            margin: { left: LEFT, right: RIGHT },
            theme: "grid",
            styles: Object.assign(gridStyles(), { fontSize: 10, cellPadding: 2, minCellHeight: 8 }),
            body: [
                [
                    { content: "Examiner", styles: { fillColor: GREY, fontStyle: "bold", minCellHeight: 8 } },
                    { content: "Signature", styles: { fillColor: GREY, fontStyle: "bold", minCellHeight: 8 } }
                ],
                ["", ""],
                ["", ""]
            ]
        });

        var footerY = Math.min(doc.lastAutoTable.finalY + 8, 290);
        doc.setFont("helvetica", "normal");
        doc.setFontSize(8);
        doc.setTextColor(MUTED[0], MUTED[1], MUTED[2]);
        doc.text("Generated by RMSM ARB Assessment Generator", 105, footerY, { align: "center" });

        return doc;
    }

    function downloadScaleSheet() {
        var sheet = readSheetFromPage();
        var doc = buildMarksheetPdf(sheet);
        var name = downloadName(sheet);
        doc.save(name);
        return name;
    }

    var root = typeof window !== "undefined" ? window : globalThis;
    root.downloadScaleSheet = downloadScaleSheet;
    root.buildMarksheetPdf = buildMarksheetPdf;
    root.readSheetFromPage = readSheetFromPage;
})();
